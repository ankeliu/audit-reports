"""Rebuild reports/index.json and reports/README.md from the accepted reports.

Deliberately carries no field that enables cross-firm comparison (no loc, effort, or rates).
"""

import datetime as dt
import json
from pathlib import Path

from .parse import ParseError, parse_file
from .paths import REPO_ROOT, REPORTS_DIR, firm_abbrev, vocab

INDEX_PATH = REPORTS_DIR / "index.json"
README_PATH = REPORTS_DIR / "README.md"


def _entry(path: Path) -> dict:
    report = parse_file(path)
    meta = report.get("report") or {}
    summary = report.get("findings_summary") or {}
    return {
        "path": path.relative_to(REPO_ROOT).as_posix(),
        "project_slug": path.parent.name,
        "client": meta.get("client"),
        "audit_firm": meta.get("audit_firm"),
        "firm_abbrev": firm_abbrev(meta.get("audit_firm")),
        "report_date": meta.get("report_date"),
        "platform": (report.get("scope") or {}).get("platform"),
        "disclosure_status": (report.get("publication") or {}).get("disclosure_status"),
        "conversion_method": (report.get("publication") or {}).get("conversion_method"),
        "findings_summary": {
            k: summary.get(k) for k in ("total", "critical", "high", "moderate", "low", "informational")
        },
        "pdf_url": meta.get("pdf_url"),
        "firm_report_url": meta.get("firm_report_url"),
    }


def report_paths() -> list[Path]:
    return sorted(p for p in REPORTS_DIR.glob("*/*.md"))


def build(today: dt.date | None = None) -> dict:
    entries = []
    for path in report_paths():
        try:
            entries.append(_entry(path))
        except ParseError as exc:
            raise SystemExit(f"{path}: {exc}") from exc
    entries.sort(key=lambda e: (e["report_date"] or "", e["path"]), reverse=True)
    return {
        "generated_at": (today or dt.date.today()).isoformat(),
        "schema_version": vocab()["schema_version"],
        "reports": entries,
    }


def render_readme(index: dict) -> str:
    lines = [
        "# Report archive",
        "",
        "Generated by `auditbank index` from [`index.json`](index.json); do not edit by hand.",
        "Each firm's linked PDF or report page is the authoritative document.",
        "",
        "| Project | Firm | Date | Findings (total) | Link |",
        "|---|---|---|---|---|",
    ]
    for e in index["reports"]:
        source = e["pdf_url"] or e["firm_report_url"]
        rel = Path(e["path"]).relative_to("reports").as_posix()
        link = f"[report]({rel})" + (f" · [firm original]({source})" if source else "")
        lines.append(
            f"| {e['client']} | {e['audit_firm']} | {e['report_date']} | {e['findings_summary']['total']} | {link} |"
        )
    if not index["reports"]:
        lines.append("| _No reports yet_ | | | | |")
    return "\n".join(lines) + "\n"


def _dump(index: dict) -> str:
    return json.dumps(index, indent=2, ensure_ascii=False) + "\n"


def write(today: dt.date | None = None) -> dict:
    index = build(today)
    INDEX_PATH.write_text(_dump(index))
    README_PATH.write_text(render_readme(index))
    return index


def is_current() -> bool:
    """True when index.json and README.md match the reports (generated_at is ignored)."""
    if not INDEX_PATH.exists() or not README_PATH.exists():
        return False
    current = json.loads(INDEX_PATH.read_text())
    fresh = build()
    current.pop("generated_at", None)
    fresh_cmp = {k: v for k, v in fresh.items() if k != "generated_at"}
    return current == fresh_cmp and README_PATH.read_text() == render_readme(fresh)
